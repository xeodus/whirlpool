import assert from 'node:assert/strict';
import { account, commitment, encryptOutput, nullifier, openOutput, packOutputs, recover, unpackOutputs } from './src/recovery.mjs';

const seedA = Uint8Array.from({ length: 32 }, (_, i) => i + 1);
const seedB = Uint8Array.from({ length: 32 }, (_, i) => i + 33);
const sender = await account(seedA);
const recipient = await account(seedB);
assert.equal((await account(seedA)).owner, sender.owner);
assert.notEqual(recipient.owner, sender.owner);
const note = { asset: 0n, amount: 60n, owner: recipient.owner, origin: 55n, rho: 50n };
const record = await encryptOutput(note, recipient.viewPublic, sender.viewPublic);
const change = { asset: 0n, amount: 38n, owner: sender.owner, origin: 55n, rho: 51n };
const changeRecord = await encryptOutput(change, sender.viewPublic, sender.viewPublic);
const packed = packOutputs([record, changeRecord]);
assert.equal(packed.length, 589);
assert.deepEqual(unpackOutputs(packed), [record, changeRecord]);
assert.throws(() => unpackOutputs(packed.subarray(0, packed.length - 1)));
const maximal = { asset: 1n, amount: (1n << 64n) - 1n, owner: recipient.owner,
  origin: (1n << 64n) - 1n, rho: recipient.owner };
const maximalRecord = await encryptOutput(maximal, recipient.viewPublic, sender.viewPublic);
assert.equal(packOutputs([maximalRecord, maximalRecord]).length, 589);
assert.deepEqual(await openOutput(maximalRecord, recipient, 'recipient'), maximal);
assert.equal(BigInt(`0x${record.commitment}`), commitment(note));
assert.deepEqual(await openOutput(record, recipient, 'recipient'), note);
assert.deepEqual(await openOutput(record, sender, 'sender'), note);
await assert.rejects(() => openOutput(record, sender, 'recipient'));
const corrupted = structuredClone(record);
corrupted.commitment = '00'.repeat(32);
await assert.rejects(() => openOutput(corrupted, recipient, 'recipient'));
const rerouted = structuredClone(record);
rerouted.recipient = record.sender;
await assert.rejects(() => openOutput(rerouted, recipient, 'recipient'));
const incoming = await recover([record], recipient, new Set());
assert.equal(incoming.length, 1);
assert.equal(incoming[0].spendable, true);
assert.equal(incoming[0].spent, false);
const spent = await recover([record], recipient, new Set([nullifier(note, recipient.spendSecret).toString()]));
assert.equal(spent[0].spent, true);
const sent = await recover([record], sender, new Set());
assert.equal(sent.length, 1);
assert.equal(sent[0].role, 'sender');
assert.equal(sent[0].spendable, false);
const senderHistory = await recover([record, changeRecord], sender, new Set());
assert.equal(senderHistory.length, 2);
assert.equal(senderHistory[1].spendable, true);
console.log('Recovery candidate: deterministic keys, recipient/sender read, commitment checks, spent status passed');
